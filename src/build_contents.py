previous = {e["id"]: e["text"] for b in blocks for c in b["chapters"] for e in c["entries"]}


def get_chapter(number):
    for block in blocks:
        for chapter in block["chapters"]:
            if chapter["number"] == number:
                return chapter
    raise KeyError(number)


added = []


def append_topics(number, topics, label):
    chapter = get_chapter(number)
    start = len(chapter["items"])
    for i, topic in enumerate(topics, start + 1):
        tid = f"{number}.{i}"
        assert tid not in previous
        chapter["items"].append(topic)
        chapter["entries"].append({
            "text": topic, "id": tid, "old_ids": [], "v2_id": None,
            "origins": [label],
        })
        added.append((tid, topic, label))


def new_chapter(block, number, title, topics, label):
    assert not any(c["number"] == number for b in blocks for c in b["chapters"])
    chapter = {"old": None, "number": number, "title": title, "items": [], "entries": []}
    block["chapters"].append(chapter)
    append_topics(number, topics, label)


